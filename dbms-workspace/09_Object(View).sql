/*
 * < VIEW 뷰 > 
 * SELECT문을 저장하는 가상의 테이블
 * 실제 데이터를 저장하는 것이 아니라, SQL문만 저장해 두었다가
 * 조회 시점에 저장한 SQL문을 실행시켜서 결과를 보여줌
 * 
 * CREATE VIEW 뷰이름
 * 		AS 서브쿼리;
 * 
 * - OR REPLACE : 뷰가 이미 존재하면 덮어쓰기
 */

GRANT CREATE VIEW TO C##MS;
-- < 뷰 만들기 >
CREATE VIEW VW_ANIMAL_INFO
    AS
SELECT 
		K.KEEPER_NAME
	  , A.ANIMAL_NAME
	  , S.SPECIES_NAME
	  , Z.ZONE_NAME
	  , A.WEIGHT_KG
	  , DECODE(A.GENDER, 'M', '수컷', 'F', '암컷')
  FROM
  		KEEPER K
  LEFT
  JOIN
  		ANIMAL A USING(KEEPER_ID)
  LEFT
  JOIN
  		ZONE Z USING(ZONE_ID)
  LEFT
  JOIN
  		SPECIES S USING(SPECIES_ID)

 SELECT * FROM VW_ANIMAL_INFO
  WHERE KEEPER_NAME = '제인구달'
  ORDER
  	 BY
  	 	ANIMAL_NAME;

